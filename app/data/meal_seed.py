def british_meal_seed(
    name: str,
    *,
    meal_type: str,
    category_ids: list[str],
    ingredients: list[dict[str, object]],
    nutrition: tuple[int, float, float, float],
    cost_gbp: float,
    prep: int,
    cook: int,
    difficulty: str = MealDifficulty.EASY.value,
    servings: int = 1,
    description: str | None = None,
    query: str | None = None,
    diet_rules_supported: list[str] | None = None,
    allergy_exclusions: list[str] | None = None,
    chef_available: bool = False,
    recipe_steps: list[str] | None = None,
) -> dict[str, object]:
    linked_product_ids: list[str] = []
    for item in ingredients:
        for product_id in item.get("linked_product_ids", []):
            if product_id not in linked_product_ids:
                linked_product_ids.append(str(product_id))

    lead = str(ingredients[0]["name"]) if ingredients else "British comfort food"
    return {
        "id": british_meal_id(name),
        "name": name,
        "hero_image_url": meal_query_image(query or name),
        "description": description
        or f"A British {meal_type} centered on {lead.lower()} and familiar comfort-food structure.",
        "meal_type": meal_type,
        "category_ids": category_ids,
        "culture_tags": ["british"],
        "diet_rules_supported": diet_rules_supported or [],
        "allergy_exclusions": allergy_exclusions or [],
        "prep_time_minutes": prep,
        "cook_time_minutes": cook,
        "difficulty": difficulty,
        "servings": servings,
        "nutrition_summary": {
            "calories": nutrition[0],
            "protein_g": nutrition[1],
            "carbs_g": nutrition[2],
            "fat_g": nutrition[3],
        },
        "estimated_costs": british_costs(cost_gbp),
        "recipe_steps": recipe_steps or build_steps(lead, meal_type),
        "ingredient_items": ingredients,
        "linked_product_ids": linked_product_ids,
        "chef_available": chef_available,
        "is_active": True,
    }


